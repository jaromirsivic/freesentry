"""Profile XTX4 presets: parameters (train / deploy) and GMAC of the fused one2one
graph at 256 / 320 / 384 for every preset x level set, plus the ``u_b`` ablations
(``p2_assist``, ``act``) and the ``xtx3u_ctrl`` recipe control.

MACs are counted with forward hooks on Conv2d / Linear (same method as XTX3's
``scripts/profile_flops.py``) on a fused deployment copy, so RepConv training
branches and the one2many head are excluded.

Usage:
    python scripts/profile_model.py [--out reports/model_budget.md] [--sizes 256 320 384]
                                    [--presets u_a u_b ...] [--device cpu]
"""

from __future__ import annotations

import argparse
from dataclasses import dataclass
from pathlib import Path
import sys
import time

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import torch  # noqa: E402

from xtx4.models import PRESETS, build_model  # noqa: E402
from xtx4.models.scaling import LEVEL_SETS  # noqa: E402
from xtx4.utils.logging import configure_logging, get_logger  # noqa: E402

logger = get_logger("profile_model")

DEFAULT_SIZES = (256, 320, 384)
PLAN_MMAC_320 = {"u_a": 395, "u_b": 765, "u_c": 1500}  # implementation_plan_fable.md section 5.2


@dataclass(slots=True)
class Row:
    label: str
    variant: str
    levels: str
    act: str
    block: str
    p2_assist: bool
    params_train: int
    params_deploy: int
    gmac: dict[int, float]
    anchors: dict[int, list[int]]  # size -> per-level N


def profile(variant: str, *, sizes: tuple[int, ...], label: str | None = None, **overrides) -> Row:
    cfg = {"variant": variant, **overrides}
    model = build_model({"model": cfg})
    spec = model.spec
    gmac = {size: model.mac_count(size) for size in sizes}
    anchors = {size: [(size // s) ** 2 for s in model.strides] for size in sizes}
    return Row(
        label=label or variant, variant=spec.name, levels=spec.levels, act=spec.act, block=spec.block,
        p2_assist=spec.p2_assist, params_train=model.num_parameters(),
        params_deploy=model.num_parameters(deploy=True), gmac=gmac, anchors=anchors,
    )


def build_rows(presets: list[str], sizes: tuple[int, ...]) -> tuple[list[Row], list[Row]]:
    main_rows: list[Row] = []
    for name in presets:
        for levels in LEVEL_SETS:
            t = time.time()
            row = profile(name, sizes=sizes, levels=levels)
            main_rows.append(row)
            logger.info(
                "%-10s %-7s params %.3fM / %.3fM deploy | %s (%.1fs)",
                name, levels, row.params_train / 1e6, row.params_deploy / 1e6,
                "  ".join(f"{s}: {g:.3f} GMAC" for s, g in row.gmac.items()), time.time() - t,
            )
    ablations: list[Row] = []
    if "u_b" in presets:
        for label, overrides in (
            ("u_b + p2_assist", {"p2_assist": True}),
            ("u_b act=hswish", {"act": "hswish"}),
            ("u_b act=silu", {"act": "silu"}),
            ("u_b P3P5 + p2_assist", {"levels": "P3P5", "p2_assist": True}),
        ):
            row = profile("u_b", sizes=sizes, label=label, **overrides)
            ablations.append(row)
            logger.info(
                "%-22s params %.3fM / %.3fM deploy | %s", label, row.params_train / 1e6,
                row.params_deploy / 1e6, "  ".join(f"{s}: {g:.3f} GMAC" for s, g in row.gmac.items()),
            )
    return main_rows, ablations


def render_markdown(main_rows: list[Row], ablations: list[Row], sizes: tuple[int, ...]) -> str:
    size_cols = " | ".join(f"GMAC @{s}" for s in sizes)
    lines = [
        "# XTX4 model budget",
        "",
        f"Generated by `scripts/profile_model.py` (torch {torch.__version__}). MACs = multiply-accumulates of the",
        "fused one2one deployment graph (Conv2d/Linear forward hooks); params `train` include RepConv branches,",
        "BatchNorm and the one2many head, `deploy` is the fused one2one graph only.",
        "",
        "## Presets x level sets",
        "",
        f"| preset | levels | block | act | params train | params deploy | {size_cols} |",
        "|---|---|---|---|---|---|" + "---|" * len(sizes),
    ]
    for r in main_rows:
        g = " | ".join(f"{r.gmac[s]:.3f}" for s in sizes)
        lines.append(
            f"| {r.variant} | {r.levels} | {r.block} | {r.act} | {r.params_train / 1e6:.3f} M | "
            f"{r.params_deploy / 1e6:.3f} M | {g} |"
        )
    lines += ["", "## u_b ablations (P3P4P5 unless stated)", "",
              f"| configuration | levels | act | p2_assist | params train | params deploy | {size_cols} |",
              "|---|---|---|---|---|---|" + "---|" * len(sizes)]
    for r in ablations:
        g = " | ".join(f"{r.gmac[s]:.3f}" for s in sizes)
        lines.append(
            f"| {r.label} | {r.levels} | {r.act} | {r.p2_assist} | {r.params_train / 1e6:.3f} M | "
            f"{r.params_deploy / 1e6:.3f} M | {g} |"
        )
    lines += ["", "## Anchor counts N per level set", "",
              "| levels | strides | " + " | ".join(f"N @{s}" for s in sizes) + " |",
              "|---|---|" + "---|" * len(sizes)]
    seen: set[str] = set()
    for r in main_rows:
        if r.levels in seen:
            continue
        seen.add(r.levels)
        cells = []
        for s in sizes:
            per_level = r.anchors[s]
            cells.append(f"{sum(per_level)} ({' + '.join(str(n) for n in per_level)})")
        lines.append(f"| {r.levels} | {list(LEVEL_SETS[r.levels])} | " + " | ".join(cells) + " |")
    lines += ["", "## Plan check (@320, P3P4P5)", "", "| preset | plan MMAC | measured MMAC | ratio |", "|---|---|---|---|"]
    for r in main_rows:
        if r.levels == "P3P4P5" and r.variant in PLAN_MMAC_320 and 320 in r.gmac:
            measured = r.gmac[320] * 1000
            plan = PLAN_MMAC_320[r.variant]
            lines.append(f"| {r.variant} | {plan} | {measured:.0f} | {measured / plan:.2f} |")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    configure_logging()
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", default="reports/model_budget.md")
    parser.add_argument("--sizes", type=int, nargs="+", default=list(DEFAULT_SIZES))
    parser.add_argument("--presets", nargs="+", default=list(PRESETS))
    parser.add_argument("--device", default="cpu", help="profiling always runs the fused copy on CPU")
    args = parser.parse_args()
    torch.set_num_threads(max(1, min(8, torch.get_num_threads())))
    sizes = tuple(int(s) for s in args.sizes)
    main_rows, ablations = build_rows(list(args.presets), sizes)
    text = render_markdown(main_rows, ablations, sizes)
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    logger.info("Wrote %s", out)
    for line in text.splitlines():
        logger.info(line)


if __name__ == "__main__":
    main()
